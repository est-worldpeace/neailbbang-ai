const assert = require("node:assert/strict");
const fs = require("node:fs");
const ts = require("typescript");
const Module = require("node:module");
const path = require("node:path");
const filename = path.join(__dirname, "lib/leftover-analysis.ts");
const code = ts.transpileModule(fs.readFileSync(filename, "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const loaded = new Module(filename, module);
loaded._compile(code, filename);
const { PROVIDED_LEFTOVERS: rows, analyzeLeftovers, predictLeftovers, validateLeftovers, parseLeftoverText } = loaded.exports;
const close = (actual, expected) => assert.ok(Math.abs(actual - expected) < 1e-8, `${actual} != ${expected}`);
const a = analyzeLeftovers(rows);
assert.equal(a.total, 424);
assert.equal(a.average, 16.96);
assert.deepEqual(a.weekdays.map(r => r.total), [51, 76, 74, 78, 145]);
assert.deepEqual(a.weeks.map(r => r.total), [74, 77, 86, 83, 104]);
assert.equal(a.daily.length, 10);
assert.equal(a.daily[0].date, "2026-09-02");
assert.equal(a.winner.key, "ridgeCalendar");
// Reference values were computed independently with NumPy from the pasted observations.
const expected = { ridgeCalendar: 5.245803004279377, mean5: 5.94, weekdayMean: 6.133333333333334, mean10: 6.17, weekday2: 6.3, ewma03: 6.516443484568271, mean3: 7.2666666666666675, weekdayLast: 8.4, last: 10.8 };
for (const s of a.scores) close(s.mae, expected[s.key]);
close(a.winner.wape, 28.052422482777416);
const expanded = analyzeLeftovers(rows, 15);
close(expanded.winner.mae, 5.96047767046404);
assert.equal(expanded.daily.length, 15);
// Changing actuals at/after an origin cannot change that origin's forecasts.
const mutated = rows.map((r, i) => i >= 15 ? { ...r, leftover: r.leftover + 100 } : r);
assert.deepEqual(analyzeLeftovers(mutated, "all").daily.find(r => r.date === "2026-09-02").predictions, a.daily[0].predictions);
assert.notEqual(analyzeLeftovers(mutated).winner.mae, a.winner.mae);
assert.throws(() => predictLeftovers(rows, "2026-09-02"), /이전/);
assert.throws(() => validateLeftovers([...rows, rows[0]]), /중복/);
assert.throws(() => parseLeftoverText("2026-02-30,3"), /날짜/);
assert.throws(() => parseLeftoverText("2026-09-01,"), /빈 수량/);
assert.throws(() => validateLeftovers([{ date: "2026-09-01", leftover: NaN }]), /정수/);
assert.throws(() => parseLeftoverText("2026-09-01,-2"));
const zero = analyzeLeftovers(rows.map(r => ({ ...r, leftover: 0 })));
assert.ok(zero.scores.every(s => s.wape === null && s.mae === 0 && s.rank === 1));
assert.equal(analyzeLeftovers(rows.slice(0, 10)).winner, null);
assert.equal(analyzeLeftovers(rows.filter(r => r.date !== "2026-09-10")).rows.length, 24);
const restored = parseLeftoverText("\uFEFF날짜,남은빵\n2026-09-13,0\n2026-09-12,10");
assert.deepEqual(restored, [{ date: "2026-09-12", leftover: 10 }, { date: "2026-09-13", leftover: 0 }]);
assert.ok(analyzeLeftovers([...rows, { date: "2026-09-14", leftover: 12 }]).scores.every(s => Number.isFinite(s.mae)));
console.log("Leftover analysis verified: 9 independent reference scores, chronological forecasts, input validation, zero totals, missing dates and updates.");
